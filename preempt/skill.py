"""Skill controller: what the ROS 2 action server wraps.

Holds the chunk buffer, asks a PolicyClient for chunks (tagged with the goal generation;
replies may arrive late), offers one action per control step to the Arbiter, and implements
the four stop modes. Per-step call order (lockstep, driven by the episode runner):
    pre_step(t, state)  -> ingest replies, terminal checks, fetch the chunk for step t
    [supervisor tick]   -> submit_goal / cancel are processed synchronously here
    act(t)              -> offer the next buffered action to the arbiter
Goal ids are generated by the client (as in ROS 2); a cancel for an id the server has not
seen yet is remembered and that goal is rejected when it arrives (cancel-before-accept).
"""
from __future__ import annotations

from collections import deque
from dataclasses import dataclass
from typing import Any, Optional, Protocol

import numpy as np

from .arbiter import RECOVERY, Arbiter
from .contracts import BUSY, Ev, GoalStatus, ProtocolConfig, StopMode


@dataclass(frozen=True)
class ChunkRequest:
    gen: int
    query_idx: int
    obs: Any
    instruction: str


@dataclass(frozen=True)
class ChunkReply:
    gen: int
    query_idx: int
    chunk: np.ndarray  # (chunk_len, 12)


class PolicyClient(Protocol):
    def request(self, req: ChunkRequest) -> None: ...
    def poll(self) -> list[ChunkReply]: ...


@dataclass
class Goal:
    goal_id: str
    gen: int
    instruction: str
    mode: StopMode
    start: int
    cancel_t: Optional[int] = None


class SkillController:
    def __init__(self, cfg: ProtocolConfig, policy: PolicyClient, arbiter: Arbiter, log,
                 lockstep: bool = True, max_wait_polls: int = 10_000):
        self.cfg, self.policy, self.arb, self.log = cfg, policy, arbiter, log
        self.lockstep, self.max_wait_polls = lockstep, max_wait_polls
        self.goal: Optional[Goal] = None
        self.statuses: dict[str, GoalStatus] = {}
        self.feedback: Optional[dict] = None
        self.late_replies = 0
        self._gen = 0
        self._buf: deque = deque()
        self._awaiting: Optional[tuple[int, int]] = None  # (gen, query_idx)
        self._qidx = 0
        self._chunk_idx = -1
        self._tomb: set[str] = set()
        self._obs = None

    # ---- goal interface (action server callbacks) ----
    @property
    def busy(self) -> bool:
        return self.goal is not None and self.statuses[self.goal.goal_id] in BUSY

    def status_of(self, goal_id: str) -> Optional[GoalStatus]:
        return self.statuses.get(goal_id)

    def submit_goal(self, t: int, goal_id: str, instruction: str, mode: StopMode) -> bool:
        reason = ("cancelled_before_accept" if goal_id in self._tomb else
                  "busy" if self.busy else
                  "owner_busy" if not self.arb.acquire(t, ("vla", self._gen + 1)) else None)
        if reason:
            self.statuses[goal_id] = GoalStatus.REJECTED
            self.log(Ev.GOAL_REJECTED, t, goal_id=goal_id, reason=reason)
            return False
        self._gen += 1
        self.goal = Goal(goal_id, self._gen, instruction, StopMode(mode), t)
        self.statuses[goal_id] = GoalStatus.ACTIVE
        self._buf.clear()
        self._awaiting, self._chunk_idx = None, -1
        self.log(Ev.GOAL_ACCEPTED, t, goal_id=goal_id, gen=self._gen, mode=self.goal.mode,
                 instruction=instruction)
        return True

    def cancel(self, t: int, goal_id: str) -> bool:
        g = self.goal
        if g is None or g.goal_id != goal_id:
            if goal_id not in self.statuses:  # not seen yet: remember, reject on arrival
                self._tomb.add(goal_id)
                self.log(Ev.A, t, goal_id=goal_id, gen=None, note="tombstone")
                return True
            self.log(Ev.CANCEL_IGNORED, t, goal_id=goal_id, status=self.statuses[goal_id])
            return False
        st = self.statuses[goal_id]
        if st != GoalStatus.ACTIVE:
            self.log(Ev.CANCEL_IGNORED, t, goal_id=goal_id, status=st)
            return False
        g.cancel_t = t
        self.statuses[goal_id] = GoalStatus.CANCELING
        self.log(Ev.A, t, goal_id=goal_id, gen=g.gen, mode=g.mode)
        self.log(Ev.CANCELING, t, goal_id=goal_id, gen=g.gen)
        if g.mode == StopMode.TRUNCATE_HOLD:
            self._finish(t, GoalStatus.CANCELED, "truncate")
        elif g.mode == StopMode.BT_SAFE_ABORT:
            self._finish(t, GoalStatus.CANCELED, "safe_abort", successor=RECOVERY)
        elif g.mode == StopMode.LANGUAGE_STOP:
            g.instruction = self.cfg.stop_instruction
            if self._awaiting is not None:  # in-flight query is not committed: re-ask with "stop"
                self._awaiting = None
        else:  # WAIT_CHUNK: an in-flight query is not committed either
            self._awaiting = None
            if not self._buf:
                self._finish(t, GoalStatus.CANCELED, "chunk_done")
        return True

    # ---- per-step ----
    def pre_step(self, t: int, state, obs=None) -> None:
        """`state` = privileged SimState; `obs` = what the policy sees (defaults to state)."""
        self._obs = state if obs is None else obs
        self._ingest(t)
        g = self.goal
        if not self.busy:
            return
        st = self.statuses[g.goal_id]
        if state.success:
            self._finish(t, GoalStatus.SUCCEEDED, "success")
        elif t - g.start >= self.cfg.reentry_budget_B:
            self._finish(t, GoalStatus.ABORTED, "budget")
        elif st == GoalStatus.CANCELING and g.mode == StopMode.WAIT_CHUNK and not self._buf:
            self._finish(t, GoalStatus.CANCELED, "chunk_done")
        elif (st == GoalStatus.CANCELING and g.mode == StopMode.LANGUAGE_STOP
              and t >= g.cancel_t + self.cfg.window_W):
            self._finish(t, GoalStatus.CANCELED, "language_window")
        self._ensure_chunk(t)

    def act(self, t: int) -> None:
        self._ensure_chunk(t)
        if self._buf and self.goal is not None:
            a = self._buf.popleft()
            self.arb.offer(t, ("vla", self.goal.gen), a)
            self.feedback = {"gen": self.goal.gen, "chunk": self._chunk_idx, "step": t}

    # ---- internals ----
    def _wants_chunk(self) -> bool:
        if not self.busy or self._buf or self._awaiting is not None:
            return False
        st = self.statuses[self.goal.goal_id]
        return st == GoalStatus.ACTIVE or (st == GoalStatus.CANCELING
                                           and self.goal.mode == StopMode.LANGUAGE_STOP)

    def _ensure_chunk(self, t: int) -> None:
        if not self._wants_chunk():
            return
        self._qidx += 1
        self._awaiting = (self.goal.gen, self._qidx)
        self.policy.request(ChunkRequest(self.goal.gen, self._qidx, self._obs, self.goal.instruction))
        if self.lockstep:  # inference does not consume control steps
            for _ in range(self.max_wait_polls):
                if self._awaiting is None:
                    return
                self._ingest(t)
            raise TimeoutError(f"policy did not reply to {self._awaiting}")

    def _ingest(self, t: int) -> None:
        for r in self.policy.poll():
            if (r.gen, r.query_idx) != self._awaiting or self.arb.is_fenced(r.gen):
                self.late_replies += 1
                self.log(Ev.LATE_REPLY, t, gen=r.gen, query_idx=r.query_idx,
                         fenced=self.arb.is_fenced(r.gen))
                continue
            chunk = np.asarray(r.chunk, dtype=float)
            if chunk.shape != (self.cfg.chunk_len, self.cfg.action_dim):
                raise ValueError(f"chunk shape {chunk.shape}, expected "
                                 f"{(self.cfg.chunk_len, self.cfg.action_dim)}")
            self._awaiting = None
            self._buf.extend(chunk)
            self._chunk_idx += 1
            self.log(Ev.FEEDBACK, t, gen=r.gen, chunk=self._chunk_idx, query_idx=r.query_idx,
                     instruction=self.goal.instruction)

    def _finish(self, t: int, status: GoalStatus, reason: str, successor=None) -> None:
        """Fence first (E, Q), then emit the terminal status: CANCELED only after Q."""
        g = self.goal
        self._buf.clear()
        self._awaiting = None
        self.arb.fence(t, g.gen, reason, successor=successor)
        self.statuses[g.goal_id] = status
        ev = {GoalStatus.CANCELED: Ev.CANCELED, GoalStatus.SUCCEEDED: Ev.GOAL_SUCCEEDED,
              GoalStatus.ABORTED: Ev.GOAL_ABORTED}[status]
        self.log(ev, t, goal_id=g.goal_id, gen=g.gen, reason=reason)
